"Generate WebView2 COM interfaces."
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def generate(header_path, output):
    spec = json.loads((ROOT / 'tools/webview2_com_surface.json').read_text())
    raw = header_path.read_bytes()
    if hashlib.sha256(raw).hexdigest() != spec['header_sha256']:
        raise ValueError('WebView2 SDK header hash mismatch')
    text = raw.decode('utf-8-sig')
    interfaces = {}
    for iid, name, base, body in re.findall(
            r'MIDL_INTERFACE\("([^"]+)"\)\s*(\w+)\s*:\s*public\s+(\w+)\s*\{(.*?)\n    \};', text, re.S):
        methods = re.findall(r'virtual\s+(?:/\*.*?\*/\s*)?HRESULT STDMETHODCALLTYPE\s+(\w+)\(\s*(.*?)\)\s*=\s*0;', body, re.S)
        interfaces[name] = (iid, base, methods)
    used = set(spec['methods'])
    selected = set()
    def visit(name):
        if name in selected or name not in interfaces:
            return
        selected.add(name)
        _, base, methods = interfaces[name]
        visit(base)
        for method, args in methods:
            if method in used:
                for ref in re.findall(r'\bICoreWebView2\w*', args):
                    visit(ref)
    for name in spec['roots']:
        visit(name)
    order = []
    def ordered(name):
        if name in order or name not in selected:
            return
        ordered(interfaces[name][1]); order.append(name)
    for name in sorted(selected):
        ordered(name)
    aliases = {'BOOL':'c_int32','UINT32':'c_uint32','UINT64':'c_uint64','INT32':'c_int32',
               'int':'c_int32','double':'c_double','float':'c_float','HRESULT':'HRESULT',
               'LPCWSTR':'c_wchar_p','LPWSTR':'c_void_p','HWND':'c_void_p','HANDLE':'c_void_p',
               'RECT':'RECT','POINT':'POINT','IUnknown':'IUnknown','IStream':'IStream',
               'EventRegistrationToken':'EventRegistrationToken','BYTE':'c_ubyte','ULONG':'c_uint32'}
    def argument(arg):
        comments = ''.join(re.findall(r'/\*.*?\*/', arg, re.S))
        flags = ['in'] if '[in]' in comments else ['out'] if '[out]' in comments else ['in']
        if '[in]' in comments and '[out]' in comments: flags=['in','out']
        clean = re.sub(r'/\*.*?\*/', '', arg, flags=re.S).strip()
        clean = re.sub(r'\bconst\s+', '', clean)
        m = re.fullmatch(r'(\w+)\s*(\**)\s*(\w+)', clean)
        if not m: raise ValueError('Unsupported argument: '+clean)
        typ, stars, name = m.groups()
        expr = aliases.get(typ, typ if typ in selected else 'c_int32' if typ.startswith('COREWEBVIEW2_') else None)
        if expr is None: raise ValueError('Unknown ABI type: '+typ)
        for _ in stars: expr='POINTER('+expr+')'
        return f'({flags!r}, {expr}, {name!r})'
    lines = ['# Generated by tools/generate_webview2_com.py; do not edit.',
             '# Microsoft.Web.WebView2 '+spec['sdk_version']+'; SDK license: LICENSES/WebView2-SDK-LICENSE.txt.',
             'from ctypes import POINTER, Structure, c_void_p, c_wchar_p, c_int32, c_uint32, c_int64, c_uint64, c_double, c_float, c_ubyte',
             'from ctypes.wintypes import RECT, POINT',
             'from comtypes import GUID, HRESULT, IUnknown, COMMETHOD',
             'class IStream(IUnknown):',
             '    _iid_ = GUID("{0000000C-0000-0000-C000-000000000046}")',
             '    _methods_ = [',
             "        COMMETHOD([], HRESULT, 'Read', (['in'], c_void_p, 'buffer'), (['in'], c_uint32, 'count'), (['out'], POINTER(c_uint32), 'read')),",
             "        COMMETHOD([], HRESULT, '_unused_Write'),",
             "        COMMETHOD([], HRESULT, 'Seek', (['in'], c_int64, 'offset'), (['in'], c_uint32, 'origin'), (['out'], POINTER(c_uint64), 'position')),",
             "        *[COMMETHOD([], HRESULT, '_unused_'+name) for name in ('SetSize','CopyTo','Commit','Revert','LockRegion','UnlockRegion','Stat','Clone')],",
             '    ]', '' ,
             '', 'class EventRegistrationToken(Structure):', "    _fields_ = [('value', c_int64)]", '']
    for name in order:
        iid, base, _ = interfaces[name]
        lines += [f'class {name}({base}):',f'    _iid_ = GUID("{{{iid}}}")','']
    for name in order:
        lines.append(name+'._methods_ = [')
        for slot,(method,args) in enumerate(interfaces[name][2]):
            if method not in used:
                lines.append(f'    COMMETHOD([], HRESULT, "_reserved_{name}_{slot}"),')
                continue
            args=re.sub(r'/\*.*?\*/',lambda m:m[0].replace(',',';'),args,flags=re.S)
            params=[] if not args.strip() or args.strip()=='void' else [argument(a) for a in args.split(',')]
            lines.append(f'    COMMETHOD([], HRESULT, {method!r}'+(' , '+', '.join(params) if params else '')+'),')
        lines += [']','']
    output.write_text('\n'.join(lines),encoding='utf8')
    print(f'{len(order)} COM interfaces generated')

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--header',required=True,type=Path)
    p.add_argument('--output',type=Path,default=ROOT/'src/webview2_com_interfaces.py')
    a=p.parse_args();generate(a.header,a.output)
